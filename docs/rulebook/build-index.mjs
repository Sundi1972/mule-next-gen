// Rebuilds search-index.js from the rulebook's chapter pages. No dependencies.
// Run after editing any chapter:  node docs/rulebook/build-index.mjs
// Each <h2 id> or <h3 id> starts an entry; its text runs to the next such heading.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
const pages = readdirSync(dir).filter((f) => f.endsWith('.html') && !f.startsWith('_'));
const decode = (s) => s.replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&rarr;/g, '→').replace(/&times;/g, '×').replace(/&middot;/g, '·');
const strip = (s) => decode(s.replace(/<script[\s\S]*?<\/script>/gi, ' ').replace(/<style[\s\S]*?<\/style>/gi, ' ').replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();

const entries = [];
const ids = new Map();
for (const page of pages.sort()) {
  const html = readFileSync(join(dir, page), 'utf8');
  const body = (html.match(/<article[\s\S]*<\/article>/i) || [html])[0];
  const re = /<h([23])\b([^>]*)\bid="([^"]+)"([^>]*)>([\s\S]*?)<\/h\1>/gi;
  const heads = [...body.matchAll(re)];
  heads.forEach((m, i) => {
    const end = i + 1 < heads.length ? heads[i + 1].index : body.length;
    const inner = m[5];
    const status = (inner.match(/class="pill [^"]*"[^>]*>([^<]+)</) || [])[1] || '';
    const title = strip(inner.replace(/<span class="pill[\s\S]*?<\/span>/g, ''));
    const text = strip(body.slice(m.index + m[0].length, end)).slice(0, 4000);
    const key = page + '#' + m[3];
    if (ids.has(key)) throw new Error('duplicate id ' + key);
    ids.set(key, true);
    entries.push({ page, id: m[3], title, status: status.trim(), text });
  });
  if (!heads.length) console.warn('no <h2 id>/<h3 id> headings in', page);
}
writeFileSync(join(dir, 'search-index.js'), '/* Generated by build-index.mjs: do not edit by hand. */\nwindow.RULEBOOK_INDEX = ' + JSON.stringify(entries) + ';\n');
console.log(`search-index.js: ${entries.length} entries from ${pages.length} pages`);
